#!/usr/bin/env python3
"""The readings of the instance's real records, taken by today's readers and stored text-free.

WHY THIS EXISTS
    The chain (`chain_development.DiskReader`) and the commit builder (`commit_builder`) each read
    the declared lines of a closing marker and of a trail integrity or security report, and a later
    change to either reader can make a real record read differently with every existing test green,
    because their tests run on synthetic records. This module takes each real record's readings by
    calling the chain's readers unchanged and, for the builder's `Environment:` and `Failing:`
    readings, reading the same parsed record (`record_declarations`) the builder reads, in the same
    `(line as written, line undressed)` form. It keeps them as a snapshot and compares records
    against it, so a changed reading is a failing check that names the record and the reading.

    The snapshot is keyed by git object id and holds no record text and no path: a reading that is
    one word is stored as written, every other text reading as its count and a SHA-256 digest. It
    is regenerated by `python3 core/tools/record_readings.py --write`.

    The readers are driven through in-memory stand-ins for the two ports they are given
    (`DiskReader(files=…, git=…)`), never re-implemented here, so what is pinned is what they
    return, not a second copy of how.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import re
import subprocess
import sys
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

import chain_development
import record_declarations

__version__ = "1.0.1"

SECTION_MARKERS = "markers"
SECTION_CODE_INTEGRITY = "code_integrity_reports"
SECTION_SECURITY = "security_reports"
SECTIONS = (SECTION_MARKERS, SECTION_CODE_INTEGRITY, SECTION_SECURITY)

# The file name each report section is found by, and so the chain step whose own declared prefix
# (`Integrity:` or `Security:`) reads it.
_REPORT_FILE_BY_SECTION = {
    SECTION_CODE_INTEGRITY: "code-integrity-report.md",
    SECTION_SECURITY: "security-report.md",
}
_SECTION_BY_REPORT_FILE = {name: section for section, name in _REPORT_FILE_BY_SECTION.items()}

SNAPSHOT_FILE_NAME = "record_readings_snapshot.json"

_MARKER_SUBJECT = re.compile(r"developer: (\S+) — implementation complete")
_TRAIL_PREFIX = ("system", "projects")
_TRAIL_TAIL = ("journey", "tobiishi", "trail")
_WORD_MAX_LENGTH = 32

# A stand-in key for the readers: they look a marker up by a change key, and a record carries none
# of its own to give them.
_STAND_IN_KEY = "record-readings"
_STAND_IN_MARKER_ID = "0" * 40

GitRunner = Callable[[Path, list[str], bytes | None], bytes]


class SnapshotError(Exception):
    """The snapshot file cannot be used: it is absent, unreadable, or not a snapshot."""


def run_git(repo: Path, arguments: list[str], stdin: bytes | None) -> bytes:
    """One read-only git call against `repo`; its standard output as bytes. Raises
    `subprocess.CalledProcessError` when git exits non-zero."""
    return subprocess.run(["git", "-C", str(repo), *arguments], input=stdin,
                          capture_output=True, check=True).stdout


@dataclass(frozen=True)
class Records:
    """The records found, each section mapping a git object id to the record's text."""

    markers: dict[str, str]
    code_integrity_reports: dict[str, str]
    security_reports: dict[str, str]

    def section(self, name: str) -> dict[str, str]:
        return getattr(self, name)


@dataclass(frozen=True)
class Mismatch:
    section: str
    record_id: str
    reading: str
    stored: object
    read: object


@dataclass(frozen=True)
class Comparison:
    mismatches: list[Mismatch]
    unknown: list[tuple[str, str]]


# --- finding the records ----------------------------------------------------------------------


def find_records(repo: Path, git: GitRunner) -> Records:
    """The closing markers reachable from `HEAD` and the trail reports in `HEAD`'s tree."""
    reports = _find_reports(repo, git)
    return Records(
        markers=_find_markers(repo, git),
        code_integrity_reports=reports[SECTION_CODE_INTEGRITY],
        security_reports=reports[SECTION_SECURITY],
    )


def _find_markers(repo: Path, git: GitRunner) -> dict[str, str]:
    listing = git(repo, ["log", "HEAD", "--format=%H%x09%s"], None).decode("utf-8")
    marker_ids = []
    for line in listing.splitlines():
        commit_id, _, subject = line.partition("\t")
        if _MARKER_SUBJECT.fullmatch(subject):
            marker_ids.append(commit_id)
    if not marker_ids:
        return {}
    stdin = "".join(f"{commit_id}\n" for commit_id in marker_ids).encode("utf-8")
    messages = git(repo, ["log", "--stdin", "--no-walk=unsorted", "--format=%x01%H%n%B"],
                   stdin).decode("utf-8")
    markers = {}
    for entry in messages.split("\x01")[1:]:
        commit_id, _, message = entry.partition("\n")
        markers[commit_id] = message
    return markers


def _find_reports(repo: Path, git: GitRunner) -> dict[str, dict[str, str]]:
    tree = git(repo, ["ls-tree", "-r", "-z", "HEAD", "--", "system/projects"], None)
    # Pairs, not a blob → section map: one blob tracked under both report names is a record in
    # each section, which is what keeping the sections apart is for.
    found: set[tuple[str, str]] = set()
    for entry in tree.decode("utf-8").split("\0"):
        header, _, path = entry.partition("\t")
        fields = header.split()
        if len(fields) != 3 or fields[1] != "blob":
            continue
        section = _report_section(path)
        if section is not None:
            found.add((section, fields[2]))
    reports: dict[str, dict[str, str]] = {
        SECTION_CODE_INTEGRITY: {}, SECTION_SECURITY: {}}
    texts = _read_blobs(repo, git, sorted({blob_id for _, blob_id in found}))
    for section, blob_id in sorted(found):
        reports[section][blob_id] = texts[blob_id]
    return reports


def _report_section(path: str) -> str | None:
    """The section a tracked path belongs to, or `None` when it is not a report under a project's
    `journey/tobiishi/trail/`."""
    parts = path.split("/")
    if len(parts) < 7 or tuple(parts[:2]) != _TRAIL_PREFIX or tuple(parts[3:6]) != _TRAIL_TAIL:
        return None
    return _SECTION_BY_REPORT_FILE.get(parts[-1])


def _read_blobs(repo: Path, git: GitRunner, blob_ids: list[str]) -> dict[str, str]:
    """The UTF-8 text of each blob, from one `git cat-file --batch`."""
    if not blob_ids:
        return {}
    stdin = "".join(f"{blob_id}\n" for blob_id in blob_ids).encode("utf-8")
    output = git(repo, ["cat-file", "--batch"], stdin)
    texts = {}
    position = 0
    for _ in blob_ids:
        header_end = output.index(b"\n", position)
        blob_id, _, size = output[position:header_end].decode("utf-8").split()
        body_start = header_end + 1
        body_end = body_start + int(size)
        texts[blob_id] = output[body_start:body_end].decode("utf-8")
        position = body_end + 1
    return texts


# --- the readings of one record ---------------------------------------------------------------


class _MarkerGit:
    """The git port `DiskReader` reads a marker through: one commit, holding `message`."""

    def __init__(self, message: str) -> None:
        self._message = message

    def commits_ahead(self, repo: str, base: str, branch: str) -> list[tuple[str, str]]:
        return [(_STAND_IN_MARKER_ID, f"developer: {_STAND_IN_KEY} — implementation complete")]

    def commit_body(self, repo: str, sha: str) -> str:
        return self._message


class _ReportFiles:
    """The files port `DiskReader` reads a report through: every path holds `text`."""

    def __init__(self, text: str) -> None:
        self._text = text

    def read_text(self, path: str) -> str:
        return self._text


def _layout() -> chain_development.ChangeLayout:
    return chain_development.ChangeLayout("/", "record-readings", _STAND_IN_KEY)


def marker_readings(message: str) -> dict[str, object]:
    """What the chain and the commit builder read from a closing marker's message, in stored
    form."""
    reader = chain_development.DiskReader(files=_ReportFiles(""), git=_MarkerGit(message))
    layout = _layout()
    record = record_declarations.parse(message)
    return {
        "suite_verdict": stored_form(reader.suite_verdict(layout)),
        "environment_kinds": [stored_form(kind)
                              for kind in reader.marker_environment_kinds(layout)],
        "language_resolved": reader.language_resolved(layout),
        "deferrals": digest_form(reader.deferrals(layout)),
        "failing_cases": digest_form(reader.failing_cases(layout)),
        "relaned_tasks": sorted(reader.relaned_tasks(layout)),
        "builder_environment": digest_form(
            [(line.raw, line.text) for line in record.read(record_declarations.ENVIRONMENT)]),
        "builder_failing": digest_form(
            [(line.raw, line.text) for line in record.read(record_declarations.FAILING)]),
    }


def report_readings(text: str, section: str) -> dict[str, object]:
    """What the chain reads from a report of `section`'s kind, in stored form, with the chain
    step whose artifact is that kind's file."""
    step = next(candidate for candidate in chain_development.DEVELOPMENT_STEPS
                if candidate.artifact == _REPORT_FILE_BY_SECTION[section])
    reader = chain_development.DiskReader(files=_ReportFiles(text), git=_MarkerGit(""))
    layout = _layout()
    return {
        "environment_kinds": [stored_form(kind)
                              for kind in reader.report_environment_kinds(layout, step)],
        "declared_verdict": stored_form(reader.declared_verdict(layout, step)),
    }


def readings_of(section: str, text: str) -> dict[str, object]:
    return marker_readings(text) if section == SECTION_MARKERS else report_readings(text, section)


# --- the text-free form -----------------------------------------------------------------------


def _is_one_word(text: str) -> bool:
    return (0 < len(text) <= _WORD_MAX_LENGTH
            and not any(character.isspace() or character == "/" for character in text))


def _digest(value: object) -> str:
    canonical = json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def stored_form(value: str | None) -> str | dict[str, object] | None:
    """One text reading as it is stored: a one-word string as written, any other string as its
    count (one item) and digest, an absent reading as `None`."""
    if value is None or _is_one_word(value):
        return value
    return {"count": 1, "sha256": _digest(value)}


def digest_form(items: list[object]) -> dict[str, object]:
    """A reading that returns lines, as its count of items and the digest of the items."""
    return {"count": len(items), "sha256": _digest(items)}


# --- the snapshot -----------------------------------------------------------------------------


def snapshot_of(records: Records) -> dict[str, dict[str, dict[str, object]]]:
    return {
        section: {record_id: readings_of(section, text)
                  for record_id, text in records.section(section).items()}
        for section in SECTIONS
    }


def serialize(snapshot: dict[str, dict[str, dict[str, object]]]) -> str:
    """The snapshot as JSON with sections and ids sorted and one record on each line."""
    lines = ["{"]
    sections = sorted(SECTIONS)
    for section_index, section in enumerate(sections):
        section_comma = "," if section_index < len(sections) - 1 else ""
        record_ids = sorted(snapshot[section])
        if not record_ids:
            lines.append(f"{json.dumps(section)}: {{}}{section_comma}")
            continue
        lines.append(f"{json.dumps(section)}: {{")
        for record_index, record_id in enumerate(record_ids):
            record_comma = "," if record_index < len(record_ids) - 1 else ""
            readings = json.dumps(snapshot[section][record_id], sort_keys=True,
                                  separators=(",", ":"), ensure_ascii=False)
            lines.append(f"{json.dumps(record_id)}: {readings}{record_comma}")
        lines.append(f"}}{section_comma}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def load_snapshot(path: Path) -> dict[str, dict[str, dict[str, object]]]:
    """The stored snapshot. A missing, unreadable or malformed file raises `SnapshotError`; it
    never answers with an empty snapshot."""
    try:
        loaded = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise SnapshotError(f"cannot read the snapshot {path.name}: {error}") from error
    if not isinstance(loaded, dict) or not all(
            isinstance(loaded.get(section), dict) for section in SECTIONS):
        raise SnapshotError(f"{path.name} is not a snapshot: it lacks one of {list(SECTIONS)}")
    return loaded


def compare(records: Records,
            snapshot: dict[str, dict[str, dict[str, object]]]) -> Comparison:
    """Each found record against the snapshot: the readings that differ, and the records the
    snapshot does not hold. A snapshot id with no found record is ignored."""
    mismatches = []
    unknown = []
    for section in SECTIONS:
        for record_id, text in sorted(records.section(section).items()):
            stored = snapshot[section].get(record_id)
            if stored is None:
                unknown.append((section, record_id))
                continue
            read = readings_of(section, text)
            for reading in sorted(set(stored) | set(read)):
                if (reading in stored) != (reading in read) or stored.get(reading) != read.get(
                        reading):
                    mismatches.append(Mismatch(
                        section, record_id, reading, stored.get(reading), read.get(reading)))
    return Comparison(mismatches, unknown)


# --- the command ------------------------------------------------------------------------------


def run(argv: list[str], *, repo_root: Path, snapshot_path: Path, git: GitRunner,
        out: io.TextIOBase) -> int:
    parser = argparse.ArgumentParser(
        prog="record_readings.py",
        description="Regenerate the snapshot of the readings of this instance's real records.")
    parser.add_argument("--write", action="store_true", required=True,
                        help=f"write {SNAPSHOT_FILE_NAME} beside this module")
    parser.parse_args(argv)
    snapshot = snapshot_of(find_records(repo_root, git))
    snapshot_path.write_text(serialize(snapshot), encoding="utf-8")
    for section in SECTIONS:
        print(f"{section}: {len(snapshot[section])}", file=out)
    return 0


def main(argv: list[str] | None = None) -> int:
    """The composition root: the repository that holds `core/tools/`, the snapshot beside this
    module, the real git."""
    here = Path(__file__).resolve()
    try:
        return run(sys.argv[1:] if argv is None else argv, repo_root=here.parents[2],
                   snapshot_path=here.with_name(SNAPSHOT_FILE_NAME), git=run_git, out=sys.stdout)
    except subprocess.CalledProcessError as error:
        print(f"record_readings: git failed: {error.stderr.decode('utf-8', 'replace').strip()}",
              file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
